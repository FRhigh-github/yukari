-- ============================================================
--  ゆかり / 「デモで入る」のゲストだけを消す（発表が終わったあとに流す）
--
--  「デモで入る」は、押すたびに「ゲスト 123」のようなアカウントを作ります（app/api/demo-login）。
--  そのアカウントは、メールアドレスの最後が @demo.yukari.invalid です。
--  それだけを選んで、書いたもの（投稿・お祝い・カード・手紙など）ごと消します。
--  ダミーの10人や、本物のメンバーのアカウントには触りません。
--
--  前は「連鎖の付いていない表」を先に片づける必要がありましたが、
--  01_schema.sql で削除したときの動きを全部決めたので、アカウントを消すだけで済みます。
--
--  何度流しても平気です。消すものが無ければ、何も起きません。
-- ============================================================

delete from auth.users
where email like '%@demo.yukari.invalid';

select count(*) as 残ったゲスト from auth.users where email like '%@demo.yukari.invalid';
