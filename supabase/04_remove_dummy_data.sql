-- ============================================================
--  ゆかり / 本番からダミーのデータを片づける（公開する前に1回だけ流す）
--
--  ハッカソンの発表のために、本番の DB にも 02_seed.sql のダミーデータと、
--  「デモで入る」で作られたゲストが入っています。公開する前に、これを片づけます。
--
--  ▼ 消えるもの
--    ・「デモで入る」のゲスト（メールの最後が @demo.yukari.invalid）
--    ・ダミーの10人（02_seed.sql の 11111111-… の人たち）
--    ・ダミーのコミュニティ2つ：「ゆかり デモ」「高校の同級生」
--      （中にある投稿・お祝い・手紙・日程調整・チャットも、連鎖で一緒に消えます。
--        本物のメンバーがこの2つに書いたものも消えます）
--    どれも、書いたもの（投稿・お祝い・カード・手紙など）ごと消えます。
--
--  ▼ 残るもの
--    ・本物のアカウントと、ほかのコミュニティ
--    ・「しばよこハッカソン9班」（班のみんなが本物のアカウントで入っているため）。
--      ただし招待コード YUKARI は GitHub に載っていて誰でも知っているので、作り直します。
--      新しいコードは、コミュニティの設定画面で見られます
--
--  ▼ 流す前に
--    下の「確かめる」だけを先に流すと、消える数が分かります。
--    消したものは元に戻せません。心配なら、先にダッシュボードの
--    Database → Backups で、今の状態が残っているかを確かめてください。
--
--  ▼ 写真のファイルについて
--    ゲストが上げた写真のファイルは、SQL からは消せません（Supabase の決まり）。
--    アプリからは見えなくなります。消したいときは Storage の各バケットで、
--    持ち主のいなくなったフォルダを消してください。
--
--  何度流しても平気です。消すものが無ければ、何も起きません。
-- ============================================================

-- ------------------------------------------------------------
--  確かめる（これだけ先に流すと、消える数が分かります）
-- ------------------------------------------------------------
select
  (select count(*) from auth.users where email like '%@demo.yukari.invalid') as ゲスト,
  (select count(*) from auth.users where id::text like '11111111-1111-4111-8111-%') as ダミーの人,
  (select count(*) from public.posts
     where community_id in ('44444444-4444-4444-8444-000000000001', '22222222-2222-4222-8222-000000000002')
       and author_id::text not like '11111111-1111-4111-8111-%') as 消えるコミュニティにある本物の人の投稿;

-- ------------------------------------------------------------
--  消す
-- ------------------------------------------------------------
delete from auth.users
where email like '%@demo.yukari.invalid';

delete from auth.users
where id::text like '11111111-1111-4111-8111-%';

delete from public.communities
where id in ('44444444-4444-4444-8444-000000000001', '22222222-2222-4222-8222-000000000002');

-- 誰でも知っている招待コードを作り直します（make_invite_code は 01_schema.sql）
update public.communities
set invite_code = public.make_invite_code()
where invite_code in ('YUKARI', 'SHIBA22');

-- 最後に、残った数を表で出します（ゲスト・ダミーの人は 0 になっているはずです）
select
  (select count(*) from auth.users where email like '%@demo.yukari.invalid') as 残ったゲスト,
  (select count(*) from auth.users where id::text like '11111111-1111-4111-8111-%') as 残ったダミーの人,
  (select count(*) from auth.users) as 全アカウント;
