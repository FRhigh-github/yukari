-- ------------------------------------------------------------
--  1. 写真の無い投稿を消す
--
--  ★ 消える前に中身を見たい場合は、先にこちらを実行してください。
--    select id, title, created_at from posts where image_url is null;
--
--  posts を消すと、その投稿への手書きリアクション(post_reactions)も
--  一緒に消えます（on delete cascade が付いているため）。
-- ------------------------------------------------------------

delete from posts where image_url is null;


-- ------------------------------------------------------------
--  2. これ以降、写真なしでは保存できないようにする
--
--  set not null = この列を空のままにできなくする、という指定です。
--  1 を先にやっておかないと、既に空の行があるので失敗します。
-- ------------------------------------------------------------

alter table posts alter column image_url set not null;


