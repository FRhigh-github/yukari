-- ============================================================
--  発表用の「デモ用コミュニティ」を作る
--
--  「デモで入る」（app/api/demo-login）で作られたゲストは、このコミュニティに入ります。
--  前は本物の班（しばよこハッカソン9班）に入れていたので、
--  ゲストから、本物のメンバーの投稿やプロフィールまで見えてしまっていました。
--
--  ▼ 中身は空っぽです
--    ダミーの人も投稿も入れていません。入ったゲストどうしで、投稿やお祝いをしていく形です。
--    （ダミーを入れたくなったら、memberships と posts を足せばそのまま使えます）
--
--  ▼ 流したあと
--    Vercel と .env.local の DEMO_COMMUNITY_ID を、下の id にしてください。
--      DEMO_COMMUNITY_ID=44444444-4444-4444-8444-000000000001
--
--  何度流しても平気です。流すたびに、デモ用コミュニティを空っぽに作り直します
--  （ゲストが書いた投稿やお祝い・ゲストの参加も、そのとき一緒に消えます。
--   ゲストのアカウントそのものは 91_clear_demo_users.sql で消します）。
-- ============================================================

-- ------------------------------------------------------------
--  0. 前に作ったデモ用コミュニティを片づけます
-- ------------------------------------------------------------
delete from post_reactions where community_id = '44444444-4444-4444-8444-000000000001';
delete from posts          where community_id = '44444444-4444-4444-8444-000000000001';
delete from memberships    where community_id = '44444444-4444-4444-8444-000000000001';
delete from communities    where id           = '44444444-4444-4444-8444-000000000001';

-- ------------------------------------------------------------
--  1. デモ用コミュニティ（空っぽ）
--     作った人はいません（created_by は空）。ゲストはみんな、ふつうのメンバーとして入ります
-- ------------------------------------------------------------
insert into communities (id, name, invite_code, created_by)
values (
  '44444444-4444-4444-8444-000000000001',
  'ゆかり デモ',
  -- 招待コード。ゲストは招待コードなしで入るので、推測されにくい長めの文字にしています
  'DEMO' || upper(substr(md5(random()::text), 1, 8)),
  null
);
